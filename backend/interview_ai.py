def generate_questions(domain="Software Engineering"):
    """
    Stable interview question generator.
    No optional args. No breaking changes.
    """

    questions = [
        f"What is your experience in {domain}?",
        "Explain a challenging project you worked on.",
        "How do you handle debugging production issues?",
        "Explain a concept you recently learned.",
        "Where do you see yourself improving technically?"
    ]

    return questions
